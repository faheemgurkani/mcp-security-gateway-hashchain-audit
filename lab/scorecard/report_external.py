"""Render lab/results/external.json into docs/results/scorecard-external.md: every gateway
scored by the same harness (src/mcp_lab/harness.py), one column each.

    uv run python -m lab.scorecard.report_external
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOTES = ROOT / "lab/scorecard/notes/external.md"
ICON = {
    "blocked": "🛡️ blocked",
    "detected": "🔎 detected",
    "undetected": "❌ undetected",
    "n/a": "–",
}
ASI = {
    "A1": "ASI10",
    "A2": "ASI10",
    "A3": "ASI10",
    "A12": "ASI10",
    "A7": "ASI03",
    "A8": "ASI03",
    "A9": "ASI02",
    "A10": "ASI04",
}


def main() -> None:
    gws = json.loads((ROOT / "lab/results/external.json").read_text())["gateways"]
    ids = [r["id"] for r in gws[0]["results"]]
    titles = {r["id"]: r["title"] for r in gws[0]["results"]}
    cell = {(g["gateway"], r["id"]): r for g in gws for r in g["results"]}
    lines = [
        "# Scorecard: MCP gateways under the same attacks",
        "",
        "Generated by `uv run python -m lab.scorecard.report_external` from "
        "`lab/results/external.json`, produced by `uv run python -m lab.adapters.score`.",
        "",
        "Every gateway wraps the same demo tool server, is configured as close to least "
        "privilege as it allows (a user may call `crm.*` only), and faces the same attacks "
        "from the same harness (`src/mcp_lab/harness.py`). Outcomes come from evidence outside "
        "the gateway: **execution** (A7–A10) from the tool server's own ledger, **tampering** "
        "(A1–A3, A12) from the gateway's *own* verifier run on a log the harness altered.",
        "",
        "External gateways are **stdio proxies** the agent launches, so they live in the "
        "`colocated` world of `scorecard.md`: an agent that can reach the log can also reach "
        "its config and the tool server. The network-boundary attacks (A4–A6) are therefore "
        "not repeated here. This table isolates what each gateway's *own controls* do.",
        "",
        "| # | Attack | ASI | " + " | ".join(f"{g['gateway']} {g['version']}" for g in gws) + " |",
        "|---|---|---|" + "---|" * len(gws),
    ]
    for i in ids:
        row = [ICON.get(cell[(g["gateway"], i)]["outcome"], "?") for g in gws]
        lines.append(f"| {i} | {titles[i]} | {ASI.get(i, '')} | " + " | ".join(row) + " |")
    lines += ["", "## Caveats per gateway", ""]
    for g in gws:
        for c in g.get("caveats", []):
            lines.append(f"- **{g['gateway']}**: {c}")
    if NOTES.exists():
        lines += ["", NOTES.read_text().strip()]
    lines += ["", "## Evidence", ""]
    for g in gws:
        lines += [f"### {g['gateway']} {g['version']} (run {g.get('run_at', '?')})", ""]
        for r in g["results"]:
            lines.append(f"- **{r['id']}** {r['outcome']}: {r['evidence']}")
        lines.append("")
    out = ROOT / "docs/results/scorecard-external.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
