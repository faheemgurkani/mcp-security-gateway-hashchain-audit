"""Render lab/results/external.json into docs/results/scorecard-external.md:
a capability comparison of the reference gateway vs. external gateways.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Reference-gateway capability on each attack (transport-independent controls).
# Values: what the reference gateway does, from the scripted scorecard + design.
REFERENCE = {
    "A1": "🔎 detected (HMAC)",
    "A2": "🔎 detected (seq/link)",
    "A3": "🔎 detected (anchor)",
    "A7": "🛡️ blocked (+field stripped)",
    "A8": "🛡️ blocked",
    "A9": "🛡️ blocked (schema)",
    "A10": "🛡️ blocked (pinning)",
    "A11": "🔎 detected (HMAC)",
}
ICON = {"blocked": "🛡️ blocked", "detected": "🔎 detected", "undetected": "❌ undetected"}


def main() -> None:
    data = json.loads((ROOT / "lab/results/external.json").read_text())
    rows = data["results"]
    lines = [
        "# Scorecard: external gateways vs. the reference gateway",
        "",
        f"Generated by `uv run python -m lab.scorecard.report_external` from "
        f"`lab/results/external.json`. Gateway under test: **{data['gateway']}** "
        f"(transport: {data['transport']}).",
        "",
        "External gateways here are **stdio proxies**: the agent launches them, so they are "
        "structurally the colocated profile (see `scorecard.md`). The network-boundary attacks "
        "(A4 config bypass, A5 kill, A6 direct) are not separately run — in a stdio deployment "
        "the agent can always reach the tool server itself, which is the colocated result.",
        "",
        "Outcome is judged the same way for every gateway: **execution** from the tool-zone "
        "execution ledger (ground truth), **tampering** from the gateway's *own* verifier.",
        "",
        "| # | Attack | reference gateway | " + data["gateway"] + " |",
        "|---|---|---|---|",
    ]
    for r in rows:
        key = "execution" if "execution" in r else "tampering"
        ext = ICON.get(r[key], r[key])
        lines.append(f"| {r['id']} | {r['title']} | {REFERENCE.get(r['id'], '–')} | {ext} |")
    lines += [
        "",
        "## Reading it",
        "",
        f"- **{data['gateway']} matches** the reference gateway on RBAC (confused deputy and the "
        "admin-access goal are blocked) and on log **edit/delete** detection: it is a genuine "
        "peer with a hash-chained audit and default-deny roles.",
        "- **It is weaker on three controls the reference gateway adds:**",
        "  - *argument validation* (A9): mcp-gate gates by tool name and role but does not "
        "validate arguments against a schema, so `crm.update` with `field=password` and a "
        "smuggled `role` field execute. The reference gateway rejects both (strict Pydantic).",
        "  - *tool-definition pinning* (A10): a rug-pulled tool stays callable; the reference "
        "gateway quarantines it.",
        "  - *truncation* (A3): a clean cut passes mcp-gate's `verify` because it does not anchor "
        "the head by default (its docs recommend external anchoring as hardening). The reference "
        "gateway catches it with the anchor.",
        "- It also does not role-filter `tools/list` (the admin tool stays visible to a user "
        "session) and signals denial as a JSON-RPC error rather than a result flag.",
        "",
        "None of this is a knock on a responsibly-scoped tool: it shows the lab discriminates "
        "between gateways on concrete, reproducible controls. See `lab/results/external.json`.",
    ]
    out = ROOT / "docs/results/scorecard-external.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
